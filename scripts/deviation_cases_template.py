def attach_case(key_text, case_code):
    """把某个偏差/OOS 案例的关键点追加到卡内 key_text 末尾。

    key_text 是卡片原本的关键点文本（可能已含 ①②③… 序号）。
    case_code 对应 DEVIATION_CASES 里的 code；若 key_flag/keypoint 为空（如纯背景类偏差），
    则原样返回 key_text，不改变卡片结构。

    返回：拼接后的文本，可直接传给 add_key_callout(doc, text)。
    """
    case = CASE_BY_CODE.get(case_code)
    if not case:
        raise KeyError("未知 case_code: %s（DEVIATION_CASES 中不存在）" % case_code)
    flag = case.get("key_flag", "")
    point = case.get("keypoint", "")
    if not point:
        return key_text
    return key_text.rstrip() + " " + flag + " " + point
